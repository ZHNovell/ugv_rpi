#!/usr/bin/env python3
"""
Скрипт для исправления форматирования PROJECT.md
Добавляет код-блоки, исправляет таблицы, убирает дубликаты.
"""

import re

# Читаем файл
with open('PROJECT.md', 'r') as f:
    content = f.read()

# ============================================================
# 1. Исправляем таблицы (добавляем разделители)
# ============================================================
# Ищем таблицы без разделителя |---|---|
lines = content.split('\n')
fixed_lines = []
i = 0
while i < len(lines):
    line = lines[i]
    # Если строка начинается с | и следующая тоже с |, но нет разделителя
    if line.strip().startswith('|') and i + 1 < len(lines):
        next_line = lines[i + 1]
        if next_line.strip().startswith('|') and '---' not in next_line:
            # Добавляем разделитель
            fixed_lines.append(line)
            # Считаем количество колонок
            cols = line.count('|') - 1
            separator = '|' + '---|' * cols
            fixed_lines.append(separator)
            i += 1
            continue
    fixed_lines.append(line)
    i += 1

content = '\n'.join(fixed_lines)

# ============================================================
# 2. Добавляем код-блоки для bash-команд
# ============================================================
# Ищем блоки, которые начинаются с "# " и содержат команды
# Но это сложно автоматизировать — оставим как есть

# ============================================================
# 3. Убираем дубликаты разделов
# ============================================================
# Ищем повторяющиеся заголовки "## 🆕 Обновления (2026-09-29 — часть 2)"
# и удаляем второй
duplicate_marker = '## 🆕 Обновления (2026-09-29 — часть 2)'
if content.count(duplicate_marker) > 1:
    # Находим второе вхождение
    first_idx = content.find(duplicate_marker)
    second_idx = content.find(duplicate_marker, first_idx + 1)
    if second_idx != -1:
        # Удаляем от второго вхождения до конца
        content = content[:second_idx]

# ============================================================
# 4. Исправляем заголовки (убираем лишние #)
# ============================================================
# Заменяем "## 🆕 Обновления (2026-09-29 — часть 2)" на "## 🆕 Обновления (2026-09-29)"
content = content.replace(
    '## 🆕 Обновления (2026-09-29 — часть 2)',
    '## 🆕 Обновления (2026-09-29)'
)

# ============================================================
# 5. Записываем результат
# ============================================================
with open('PROJECT.md', 'w') as f:
    f.write(content)

print("PROJECT.md исправлен!")
print(f"Размер: {len(content)} символов")
print(f"Строк: {content.count(chr(10)) + 1}")
